  if (t === 's4') return (o.mag && o.abs) ? `${s.nm}은(는) 겉보기 ${fmt(s.m)}, 절대 ${fmt(s.M)}로 서로 달라. 10 pc에 있는 별이라면?` : '겉보기 등급과 절대 등급을 둘 다 재서 비교해 봐.';
